# -----------------------
# LAGRANGE FUNCTION
# -----------------------
def lagrange(x_values, y_values, x):
    n = len(x_values)
    result = 0.0

    for i in range(n):
        term = float(y_values[i])

        for j in range(n):
            if j != i:
                term *= (x - x_values[j]) / (x_values[i] - x_values[j])

        result += term

    return result

