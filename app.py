@app.route('/calculator', methods=['GET', 'POST'])
def calculator():
    result = ""
    total = 0.0

    if request.method == 'POST':

        x_values = list(map(float, request.form['x_values'].split(',')))
        y_values = list(map(float, request.form['y_values'].split(',')))
        target_x = float(request.form['target_x'])

        n = len(x_values)

        steps = "<h2>📘 Step-by-Step Solution</h2>"

        for i in range(n):
            Li = 1.0
            numerator = []
            denominator = []

            for j in range(n):
                if j != i:
                    Li *= (target_x - x_values[j]) / (x_values[i] - x_values[j])
                    numerator.append(f"(x - {x_values[j]})")
                    denominator.append(f"({x_values[i]} - {x_values[j]})")

            term = y_values[i] * Li
            total += term

            num = " \\cdot ".join(numerator)
            den = " \\cdot ".join(denominator)

            steps += f"""
            <div style="
                background:#eaf2f8;
                padding:15px;
                margin-bottom:15px;
                border-radius:10px;
                border-left:6px solid #3498db;
            ">

            <h3 style="color:#3498db;">Step {i+1}</h3>

            <p>
            $$L_{i}(x)=\\frac{{{num}}}{{{den}}}$$
            </p>

            <p>
            $$L_{i}({target_x})={Li:.6f}$$
            </p>

            <p>
            $$y_{i}L_{i}={y_values[i]}\\times{Li:.6f}={term:.6f}$$
            </p>

            </div>
            """

        steps += f"""
        <div style="
            background:#e8f5e9;
            padding:20px;
            border-radius:10px;
            border-left:6px solid #2ecc71;
        ">
        <h2 style="color:#27ae60;">Final Answer</h2>
        <p>$$P({target_x})={total:.6f}$$</p>
        </div>
        """

        result = steps

    return calculator_template.format(result=result)

